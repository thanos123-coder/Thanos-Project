// Builds web/fx/icons.js: an inline sprite of every Lucide icon the prototype uses.
// Usage: node web/tools/build-icons.mjs <path to lucide-static/icons>
// (get it with `npm pack lucide-static` and unpack, or from node_modules/lucide-static/icons)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const webDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const iconsDir = process.argv[2];
if (!iconsDir || !fs.existsSync(iconsDir)) {
  console.error('Pass the lucide-static icons directory as the first argument.');
  process.exit(1);
}

const sources = ['index.html', 'app.js', 'data.js', ...fs.readdirSync(path.join(webDir, 'fx')).filter((f) => /\.(js|html)$/.test(f) && f !== 'icons.js').map((f) => `fx/${f}`)];
const text = sources.map((f) => fs.readFileSync(path.join(webDir, f), 'utf8')).join('\n');

const names = new Set();
for (const m of text.matchAll(/#i-([a-z0-9-]+)/g)) names.add(m[1]);
for (const m of text.matchAll(/\bic\(\s*'([a-z0-9-]+)'/g)) names.add(m[1]);
for (const m of text.matchAll(/\bicon:\s*'([a-z0-9-]+)'/g)) names.add(m[1]);
for (const m of text.matchAll(/data-icon="([a-z0-9-]+)"/g)) names.add(m[1]);
// Values of *_ICON lookup tables, e.g. const TAKE_ICON = { good: 'check' }
for (const m of text.matchAll(/[A-Z_]+_ICONS? = \{([^}]+)\}/g)) for (const v of m[1].matchAll(/'([a-z0-9-]+)'/g)) names.add(v[1]);

const missing = [];
const symbols = [...names].sort().map((n) => {
  const file = path.join(iconsDir, `${n}.svg`);
  if (!fs.existsSync(file)) { missing.push(n); return ''; }
  const svg = fs.readFileSync(file, 'utf8');
  const inner = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').trim();
  return `<symbol id="i-${n}" viewBox="0 0 24 24">${inner}</symbol>`;
}).filter(Boolean);
if (missing.length) console.warn(`Not found in Lucide (skipped): ${missing.join(', ')}`);

const out = `/* Generated by web/tools/build-icons.mjs. Do not edit by hand.
   Icons: Lucide (ISC license, lucide.dev). Loaded first in <body> so icons render without a flash. */
document.body.insertAdjacentHTML('afterbegin', ${JSON.stringify(`<svg xmlns="http://www.w3.org/2000/svg" width="0" height="0" style="position:absolute" aria-hidden="true">${symbols.join('')}</svg>`)});
`;
fs.writeFileSync(path.join(webDir, 'fx', 'icons.js'), out);
console.log(`Wrote fx/icons.js with ${symbols.length} icons`);
